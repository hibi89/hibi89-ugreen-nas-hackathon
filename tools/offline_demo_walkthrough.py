"""Generate a reproducible ProjectReady demo from the ACTUAL offline engine.

SYNTHETIC ONLY. No NAS, SDK, customer-file, shell-command, or network access.
The SDK_VERIFIED flag below is ONLY a mock hypothesis to exercise a branch
of the existing engine; it is NOT evidence of official tool registration.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from projectready.combined_report import assemble
from projectready.policy_guard import Policy
from projectready.presence import EvidenceOrigin, FileEvidence, ScanEnvelope
from projectready.readiness import Requirement, ScanStatus

REQUIREMENTS = (
    Requirement("brief", "delivery/brief.pdf"),
    Requirement("handoff", "delivery/handoff.pdf"),
)


def scenario(name: str, summary: str, *, paths: tuple[str, ...],
             status: ScanStatus = ScanStatus.COMPLETE,
             permission: bool = True,
             pagination_complete: bool = True) -> dict:
    # Hypothetical trusted-adapter FLAGS only. No adapter has been verified.
    scan = ScanEnvelope(
        authorized_root_ref="SYNTHETIC_ROOT_NOT_A_NAS",
        scope_prefix="delivery",
        status=status,
        evidence_origin=EvidenceOrigin.SDK_VERIFIED,
        adapter_verified=True,
        permission_granted=permission,
        pagination_exhausted=pagination_complete,
        complete_scope=pagination_complete,
        observations=tuple(
            FileEvidence(path, "synthetic-proof-" + str(i + 1))
            for i, path in enumerate(paths)
        ),
        scan_reference="SYNTHETIC_SCAN_NOT_AN_OFFICIAL_RECEIPT",
    )
    policy = Policy(
        folder_selected=permission,
        authorized_metadata_read=permission,
        official_adapter_validated=permission,
    )
    result = assemble(REQUIREMENTS, scan, policy)
    return {
        "id": name,
        "hypothesis": summary,
        "overall": result.overall.value,
        "presence": [
            {"id": c.requirement_id, "verdict": c.verdict.value,
             "evidence_refs": list(c.evidence_refs), "note": c.explanation}
            for c in result.presence.checks
        ],
        "versions": [
            {"id": v.requirement_id, "signal": v.signal.value,
             "candidate_count": len(v.candidates)}
            for v in result.versions
        ],
        "permission_gate": result.policy_decision.value,
        "privacy_gate": result.privacy_check.value,
        "authoritative_version_gate": result.version_verification.value,
        "limitations": list(result.limitations),
        "is_real_nas_validation": result.is_real_nas_validation,
    }


def build() -> dict:
    base = ("delivery/brief.pdf", "delivery/handoff.pdf")
    cases = [
        scenario("all_present", "Hypothetically authorized complete listing", paths=base),
        scenario("confirmed_missing", "Hypothetical complete listing omits handoff",
                 paths=("delivery/brief.pdf",)),
        scenario("partial_listing", "Truncated listing cannot prove missing handoff",
                 paths=("delivery/brief.pdf",), status=ScanStatus.PARTIAL,
                 pagination_complete=False),
        scenario("permission_denied", "No permission: never assert presence or absence",
                 paths=(), status=ScanStatus.DENIED, permission=False,
                 pagination_complete=False),
        scenario("version_ambiguity", "Two extra possible revisions demand owner decision",
                 paths=base + ("delivery/brief_v2.pdf", "delivery/brief_final.pdf")),
    ]
    return {
        "kind": "PROJECTREADY_OFFLINE_SYNTHETIC_DEMO",
        "status": "NOT_OFFICIAL_VALIDATION",
        "official_ugos_creator": "NOT_EVIDENCED",
        "official_checker": "NOT_RUN",
        "real_nas": "NOT_RUN",
        "devpost": "NOT_SUBMITTED",
        "fixture_warning": (
            "Invented paths, refs and trusted-adapter flags; these exercise only "
            "existing Python logic, not UGREEN registered-agent behavior."
        ),
        "cases": cases,
    }


def markdown(doc: dict) -> str:
    lines = [
        "# ProjectReady NAS — runnable offline demonstration",
        "",
        "**SYNTHETIC ONLY — NOT a UGREEN NAS execution or official-tool result.**",
        "",
        doc["fixture_warning"],
        "",
        "The following five outputs are generated by the actual "
        "`src/projectready/combined_report.py` engine on fixed synthetic fixtures.",
        "No real user/NAS files, data or tokens were read.",
        "",
        "| Hypothetical case | Brief | Handoff | Version check | Overall |",
        "|---|---|---|---|---|",
    ]
    for case in doc["cases"]:
        files = {row["id"]: row["verdict"] for row in case["presence"]}
        version = {row["id"]: row["signal"] for row in case["versions"]}
        lines.append("| " + " | ".join([
            "`" + case["id"] + "`", files["brief"], files["handoff"],
            version["brief"], case["overall"]
        ]) + " |")
    lines += [
        "",
        "## What each simulated case proves",
        "",
        "- **All present**: both path checks PASS, but overall stays **NEEDS_REVIEW** "
        "because actual privacy and authoritative version checks remain NOT_CHECKED.",
        "- **Confirmed missing**: only a *hypothetically* complete/authorized listing "
        "can classify missing handoff FAIL; overall **BLOCKED**.",
        "- **Partial listing**: the same absent name becomes **NOT_CHECKED**, not FAIL.",
        "- **Permission denied**: neither presence nor absence can be asserted.",
        "- **Version ambiguity**: a present exact brief with plausible revisions "
        "triggers **CANDIDATES_REVIEW**; do not select a final version by name.",
        "",
        "## Actual output and validation boundary",
        "",
        "- Source execution: `python tools/offline_demo_walkthrough.py --output-dir /path/to/empty/folder`.",
        "- Only creates `demo_report.json` and `demo_report.md` inside the caller-selected "
        "local output directory; the script itself performs no filesystem scan, API call or upload.",
        "- The JSON preserves per-file simulated proof references and limitations; these references "
        "are invented and never valid for actual NAS access.",
        "- All cases retain `is_real_nas_validation=false`, `privacy_gate=NOT_CHECKED` "
        "and `authoritative_version_gate=NOT_CHECKED`.",
        "- Actual first-party UGOS Creator generation, official checker, registered Agents and "
        "Devpost submission are **NOT_EVIDENCED / NOT_RUN / NOT_SUBMITTED**.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Synthetic-only offline walk-through")
    parser.add_argument("--output-dir", type=Path, required=True)
    args = parser.parse_args()
    out = args.output_dir
    out.mkdir(parents=True, exist_ok=True)
    doc = build()
    (out / "demo_report.json").write_text(
        json.dumps(doc, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (out / "demo_report.md").write_text(markdown(doc), encoding="utf-8")
    print("OFFLINE DEMO: 5 SYNTHETIC CASES, NO REAL NAS OR SDK; " + str(out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
