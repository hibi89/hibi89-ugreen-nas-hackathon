"""G38 safety gate never invents entrant release approval."""
import tempfile,sys,unittest
from pathlib import Path
from unittest.mock import patch
ROOT=Path(__file__).resolve().parents[1];sys.path.insert(0,str(ROOT/"tools"))
import g38_release_gate as g
class G38ReleaseTests(unittest.TestCase):
 def test_approval_never_autogenerated(self):
  x=g.immutable_blockers()
  self.assertEqual(x["explicit_Devpost_submission_permission"],"NOT_GIVEN")
  self.assertEqual(x["Devpost_submission_receipt"],"NOT_SUBMITTED")
  self.assertEqual(x["UGREEN_kit_platform_license_and_applicable_terms"],"NOT_CLEARED")
 def test_hold_on_actual_pending(self):
  self.assertEqual(g.status_for(g.immutable_blockers()),"HOLD_EXTERNAL_REVIEW_REQUIRED_NOT_SUBMITTED")
 def test_even_spoofed_approved_values_do_not_grant_permission(self):
  all_green={k:"CLEARED" for k in g.immutable_blockers()}
  self.assertEqual(g.status_for(all_green),"HOLD_FOR_SEPARATE_OWNER_ACTION_NOT_SUBMITTED")
 def test_reject_missing_artifact_folder(self):
  with tempfile.TemporaryDirectory() as t:
   with self.assertRaisesRegex(ValueError,"Missing/unsafe artifact member"):
    g.audit(Path(t))
 def test_no_network_or_submitting_code(self):
  source=(ROOT/"tools/g38_release_gate.py").read_text(encoding="utf-8")
  for forbidden in ("requests.post","urllib.request.urlopen","subprocess.run","gh api","devpost-submit","GenUI."):
   self.assertNotIn(forbidden,source)
 def test_byte_pin(self):
  self.assertEqual(len(g.G36_SHA),64)
  self.assertEqual(len(g.SHA_PDF),64)
  self.assertNotEqual(g.SHA_PDF,g.SHA_ZIP)
if __name__=="__main__":unittest.main()
